#pragma once

#include <cstdint>
#include <cstddef>
#include <string>
#include <vector>

// ============================================================
// Чистая логика проекта — без зависимостей от Arduino/Wire/SPI.
// Компилируется на ESP32 и на хосте (native).
// ============================================================

// ------------------------------------------------------------
// Структура одного измерения (Этап 7)
// ------------------------------------------------------------
// Ровно 10 байт. packed обязателен — без него компилятор добавит
// padding и sizeof(Measurement) станет 12 (КРИТИЧЕСКОЕ #5).
struct __attribute__((packed)) Measurement {
    uint32_t timestamp;     // секунды с старта (uptime). Обнуляется при power-off.
    uint16_t co2;           // ppm (валидный диапазон 0..10000)
    int16_t  temp_x10;      // T × 10 (235 = 23.5°C)
    uint8_t  humidity;      // RH в % (0..100)
    uint8_t  flags;         // резерв
};
static_assert(sizeof(Measurement) == 10, "Measurement must be 10 bytes");

// Валидация: значения вне диапазона — мусор от глюка датчика
// или плохого контакта; такие не сохраняем и не рисуем.
bool is_measurement_valid(const Measurement& m);

// ------------------------------------------------------------
// File numbering (Этап 7)
// ------------------------------------------------------------
// Файлы данных называются /data/measurements_NNN.bin, где NNN —
// трёхзначный номер с ведущими нулями (001..999).

// "/data/measurements_001.bin" → "/data/measurements_001.bin"
//                       ^номер^                   ^номер^
std::string make_filename(int number);

// "/data/measurements_007.bin" → 7
// строка без правильного формата → -1
int extract_file_number(const std::string& path);

// Просто +1, обёртка для семантической ясности.
int next_file_number(int current);

// ------------------------------------------------------------
// Ротация файлов (Этап 8)
// ------------------------------------------------------------
// Когда файлов больше max_files — возвращает номер самого старого
// (с наименьшим значением), который надо удалить. Иначе возвращает -1.
// На пустом списке тоже -1.
int oldest_file_to_remove(const std::vector<int>& numbers, int max_files);

// ------------------------------------------------------------
// Downsampling для графиков (Этап 9)
// ------------------------------------------------------------
// Простое усреднение по равным окнам. Если input короче target —
// каждый бакет получает один элемент (по сути «растягиваем»).
// Если target <= 0 — возвращаем пустой vector. Если input пустой —
// возвращаем vector нулей нужной длины (чтобы вызвавший мог
// безопасно отрисовать пустой график).
std::vector<float> downsample(const std::vector<float>& input, int target_size);

// ------------------------------------------------------------
// Алерт VENTILATE с гистерезисом (Этап 12)
// ------------------------------------------------------------
// Возвращает новое состояние алерта:
//   off → on  при co2 > 1500
//   on  → off при co2 < 1300
// В «гистерезисной зоне» 1300..1500 состояние не меняется —
// это убирает дребезг, когда CO2 колеблется вокруг порога.
bool update_alert_state(bool current, int co2);

// ------------------------------------------------------------
// Светофоры (Этап 11)
// ------------------------------------------------------------
// Возвращают уровень: 0 = плохо, 1 = терпимо, 2 = хорошо.
// Пороги жёстко зашиты под значения из CLAUDE.md, чтобы тесты
// чистой логики не зависели от #define в main.cpp.
//   CO2:        good < 800, ok < 1500, иначе bad
//   Temperature good 20..24°C, ok 18..26°C, иначе bad
//   Humidity:   good 40..60%, ok 30..70%, иначе bad
int get_co2_traffic_level(int co2);
int get_temp_traffic_level(float temp_c);
int get_humidity_traffic_level(int humidity_pct);

// ------------------------------------------------------------
// Навигация по 9 экранам (Этап 6)
// ------------------------------------------------------------
int cycle_param(int current_screen);
int cycle_period(int current_screen);
